const {chromium}=require('playwright');
const path=require('path');const {pathToFileURL}=require('url');const fs=require('fs');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(root,'output/reader/index.html')).href);
 await page.screenshot({path:path.join(root,'qa/desktop-home.png')});
 await page.getByRole('link',{name:'从第一章开始阅读 →'}).click();
 await page.screenshot({path:path.join(root,'qa/desktop-chapter.png')});
 await page.locator('#search').click();
 await page.locator('#search-input').fill('缓存一致性');
 await page.waitForFunction(()=>document.querySelectorAll('.search-result').length>0);
 const searchCount=await page.locator('.search-result').count();
 await page.locator('#search-close').click();
 await page.locator('#larger').click();
 const font=await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--font'));
 await page.locator('#mode').click();
 const stacked=await page.locator('body').evaluate(x=>x.classList.contains('stacked'));
 await page.locator('#mode').click();
 const zhOnly=await page.locator('.pair .en').first().isVisible()===false;
 await page.locator('#mode').click();await page.locator('#mode').click();
 await page.locator('#theme').click();
 await page.screenshot({path:path.join(root,'qa/night-chapter.png')});
 await page.locator('#theme').click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(root,'qa/mobile-chapter.png')});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 await page.locator('#navtoggle').click();
 const mobileNav=await page.locator('.sidebar').isVisible();
 const navClearOfToolbar=await page.evaluate(()=>document.querySelector('.sidebar').getBoundingClientRect().top>=document.querySelector('.topbar').getBoundingClientRect().bottom-1);
 await page.locator('#navtoggle').click();
 await page.goto(pathToFileURL(path.join(root,'output/reader/ch06.html')).href+'#p124b04');
 await page.locator('#p124b04').scrollIntoViewIfNeeded();
 await page.evaluate(()=>document.documentElement.style.scrollBehavior='auto');
 await page.locator('#p124b04').evaluate(x=>x.scrollIntoView());
 await page.screenshot({path:path.join(root,'qa/mobile-table.png')});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(pathToFileURL(path.join(root,'output/reader/ch03.html')).href+'#p046b01');
 await page.evaluate(()=>document.documentElement.style.scrollBehavior='auto');
 await page.locator('#p046b01').evaluate(x=>x.scrollIntoView());
 await page.screenshot({path:path.join(root,'qa/desktop-formula.png')});
 await page.goto(pathToFileURL(path.join(root,'output/reader/index.html')).href);
 const resumeAvailable=await page.locator('#resume').isVisible();
 const result={searchCount,font,stacked,zhOnly,mobileNav,navClearOfToolbar,resumeAvailable,mobileHorizontalOverflow:overflow,jsErrors:errors};
 fs.writeFileSync(path.join(root,'qa/browser-checks.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));
 await browser.close();
 if(overflow||errors.length||!stacked||!zhOnly||!mobileNav||!navClearOfToolbar)process.exitCode=1;
})();
